static void adc_cache_invalidate(void)
{
    adc_cache = (sensing_adc){0};
    adc_cache_valid = false;
    adc_tick_at = 0u;
}

static void modify(uintptr_t address, uint32_t clear, uint32_t set)
{
    hw_write32(address, (hw_read32(address) & ~clear) | set);
}

static bool expired(uint32_t start, uint32_t budget)
{
    return (uint32_t)(hw_micros() - start) >= budget;
}

static void delay_us(uint32_t duration)
{
    uint32_t start = hw_micros();
    while (!expired(start, duration)) hw_relax();
}

static void reset_peripheral(uintptr_t address, uint32_t mask)
{
    modify(address, 0, mask);
    (void)hw_read32(address);
    modify(address, mask, 0);
    (void)hw_read32(address);
}

static void i2c_configure(void)
{
    reset_peripheral(RCC + 0x2c, I2C_CLOCK);
    hw_write32(I2C1, 0); /* PE=0 while timing is changed. */
    hw_write32(I2C1 + 4, 0);
    hw_write32(I2C1 + 0x10, I2C_TIMING);
    hw_write32(I2C1 + 0x1c, I2C_CLEAR); /* ICR; ISR at +18 is not W1C. */
    hw_write32(I2C1, I2C_CONFIGURATION); /* Selected filter profile, PE enabled last. */
}

static bool i2c_wait(uint32_t mask, bool set, uint32_t start)
{
    for (;;) {
        uint32_t status = hw_read32(I2C1 + 0x18);
        /* fast17 (review F-7a, a deferred item): errors, then completion, then the deadline. A transfer that completed
         * while this wait was preempted past its budget is accepted (the tick stamps the sample time afterwards). */
        if (status & I2C_ERRORS) {
            if (status & 0x10u) last_faults |= SENSING_FAULT_I2C_NACK;
            if (status & (I2C_ERRORS & ~0x10u)) last_faults |= SENSING_FAULT_I2C_BUS;
            return false;
        }
        if (((status & mask) != 0) == set) return true;
        if (expired(start, ENCODER_BUDGET_US)) {
            last_faults |= SENSING_FAULT_I2C_TIMEOUT;
            return false;
        }
        hw_relax();
    }
}

static void i2c_cleanup(void)
{
    uint32_t start = hw_micros();
    if (hw_read32(I2C1 + 0x18) & I2C_BUSY) {
        modify(I2C1 + 4, 1u << 13, 1u << 14); /* Request STOP, never another START. */
        while (hw_read32(I2C1 + 0x18) & I2C_BUSY) {
            if (expired(start, I2C_CLEANUP_US)) break;
            hw_relax();
        }
    }
    hw_write32(I2C1 + 0x1c, I2C_CLEAR);
    i2c_configure(); /* Release peripheral ownership after every failed transfer. */
    if (hw_read32(I2C1 + 0x18) & I2C_BUSY) last_faults |= SENSING_FAULT_I2C_STUCK;
}

static bool wait_register(uintptr_t address, uint32_t mask, bool set,
                          uint32_t start, uint32_t budget)
{
    for (;;) {
        uint32_t value = hw_read32(address);
        if (((value & mask) != 0) == set) return true;   /* fast17 (F-7a): completion before the deadline */
        if (expired(start, budget)) return false;
        hw_relax();
    }
}

bool sensing_init(void)
{
    initialized = false;
    adc_usable = false;
    adc_cache_invalidate();
    sensor_conf_saved = false;
    sensor_conf_original = 0;
    last_faults = 0;
    modify(RCC + 0x34, 0, 3); /* GPIOA/B only. */
    (void)hw_read32(RCC + 0x34);
    modify(RCC + 0x3c, 0, I2C_CLOCK);
#if SENSING_FAST_I2C
    modify(RCC + 0x40, 0, ADC_CLOCK | 1u); /* ADC and SYSCFG clocks. */
    (void)hw_read32(RCC + 0x40);
    modify(RCC + 0x54, 0x3000u, 0u); /* I2C1 kernel=PCLK64. */
    modify(SYSCFG, 0u, 0x30000u); /* PB6/PB7 Fm+ drive only; preserve other pins. */
#else
    modify(RCC + 0x40, 0, ADC_CLOCK);
    (void)hw_read32(RCC + 0x40);
    modify(RCC + 0x54, 0x3000u, 0x2000u); /* I2C1 kernel=HSI16, independent of PLL64. */
#endif

    /* Configure electrical properties before connecting alternate outputs. */
    modify(GPIOB + 4, 0, 0xc0u);
    modify(GPIOB + 8, 0xf000u, 0xa000u);
    modify(GPIOB + 0xc, 0xf00cu, 0x5000u);
    modify(GPIOB + 0x20, 0xff000000u, 0x66000000u);
    modify(GPIOB, 0xf00cu, 0xa00cu); /* PB1 analog, PB6/7 AF. */
    modify(GPIOA + 0xc, 15, 0);
    modify(GPIOA, 15, 15); /* PA0/1 analog. */
    i2c_configure();
#if SENSING_FAST_I2C
    if (hw_read32(I2C1 + 0x10u) != I2C_TIMING ||
        (hw_read32(I2C1) & 0x1f01u) != I2C_CONFIGURATION ||
        (hw_read32(RCC + 0x54u) & 0x3000u) != 0u ||
        (hw_read32(SYSCFG) & 0x30000u) != 0x30000u) {
        last_faults |= SENSING_FAULT_I2C_BUS;
        return false;
    }
#endif
    if (!i2c_wait(I2C_BUSY, false, hw_micros())) {
        i2c_cleanup();
        return false;
    }

    reset_peripheral(RCC + 0x30, ADC_CLOCK);
    hw_write32(ADC1 + 4, 0); /* No ADC interrupt. */
    hw_write32(ADC1 + 0xc, 0); /* 12-bit, right, software single, no DMA. */
    hw_write32(ADC1 + 0x10, 0x80000000u); /* CKMODE10: PCLK64/4 = ADC16MHz. */
    /* Both sample times79.5cycles:4.969us acquisition meets VREFINT >=4us.
     * Four12-bit conversions:23us nominal, excluding MMIO/trigger overhead. */
    hw_write32(ADC1 + 0x14, 0x66);
    modify(ADC_CCR, 0, 1u << 22);
    hw_write32(ADC1 + 8, ADC_REGULATOR);
    delay_us(20); /* DS12991 Table56: regulator startup max20us. */
    hw_write32(ADC1 + 8, ADC_REGULATOR | ADC_CAL);
    if (!wait_register(ADC1 + 8, ADC_CAL, false, hw_micros(), ADC_INIT_BUDGET_US)) goto adc_fail;
    delay_us(2); /* At least four ADC clocks between calibration and ADEN. */
    hw_write32(ADC1, 1); /* Clear ADRDY before enabling. */
    hw_write32(ADC1 + 8, ADC_REGULATOR | 1);
    if (!wait_register(ADC1, 1, true, hw_micros(), ADC_INIT_BUDGET_US)) goto adc_fail;
    delay_us(12); /* DS12991 Table25: VREFINT buffer startup after ADC enable. */
    initialized = true;
    adc_usable = true;
    return true;
adc_fail:
    last_faults |= SENSING_FAULT_ADC_INIT | SENSING_FAULT_ADC_TIMEOUT;
    reset_peripheral(RCC + 0x30, ADC_CLOCK);
    return false;
}

/* One complete word transaction; publish only after its own STOP.
 * Transfer deadline is200us default/120us fast plus <=10us STOP cleanup. */
static bool i2c_read_word(uint8_t reg, uint16_t *word)
{
    uint32_t start = hw_micros();
    if (!i2c_wait(I2C_BUSY, false, start)) goto fail;
    hw_write32(I2C1 + 0x1c, I2C_CLEAR);
    hw_write32(I2C1 + 4, 0x0001206cu); /* Address36, write one byte, START. */
    if (!i2c_wait(2, true, start)) goto fail;
    hw_write32(I2C1 + 0x28, reg);
    if (!i2c_wait(0x40, true, start)) goto fail;
    hw_write32(I2C1 + 4, 0x0202246cu); /* Read2, repeated START, AUTOEND. */
    if (!i2c_wait(4, true, start)) goto fail;
    uint16_t value = (uint16_t)((hw_read32(I2C1 + 0x24) & 255u) << 8);
    if (!i2c_wait(4, true, start)) goto fail;
    value |= (uint16_t)(hw_read32(I2C1 + 0x24) & 255u);
    if (!i2c_wait(I2C_STOPF, true, start)) goto fail;
    hw_write32(I2C1 + 0x1c, I2C_STOPF);
    hw_write32(I2C1 + 4, 0);
    *word = value;
    return true;
fail:
    i2c_cleanup();
    return false;
}

/* STATUS (0x0B) + RAW ANGLE (0x0C/0x0D) in one transaction: one extra byte on the
 * bus (~10 us at Fm+). AS5600 STATUS: MH bit3 (too strong), ML bit4 (too weak),
 * MD bit5 (magnet detected). No CRC exists on this device. */
bool sensing_read_encoder_status(uint16_t *raw, uint8_t *status)
{
    last_faults = 0;
    if (!raw || !status) { last_faults = SENSING_FAULT_ARGUMENT; return false; }
    *raw = 0; *status = 0;
    if (!initialized) { last_faults = SENSING_FAULT_NOT_INITIALIZED; return false; }
    uint32_t start = hw_micros();
    if (!i2c_wait(I2C_BUSY, false, start)) goto fail;
    hw_write32(I2C1 + 0x1c, I2C_CLEAR);
    hw_write32(I2C1 + 4, 0x0001206cu); /* Address36, write one byte, START. */
    if (!i2c_wait(2, true, start)) goto fail;
    hw_write32(I2C1 + 0x28, 0x0bu);
    if (!i2c_wait(0x40, true, start)) goto fail;
    hw_write32(I2C1 + 4, 0x0203246cu); /* Read3, repeated START, AUTOEND. */
    if (!i2c_wait(4, true, start)) goto fail;
    uint8_t st = (uint8_t)(hw_read32(I2C1 + 0x24) & 255u);
    if (!i2c_wait(4, true, start)) goto fail;
    uint16_t value = (uint16_t)((hw_read32(I2C1 + 0x24) & 255u) << 8);
    if (!i2c_wait(4, true, start)) goto fail;
    value |= (uint16_t)(hw_read32(I2C1 + 0x24) & 255u);
    if (!i2c_wait(I2C_STOPF, true, start)) goto fail;
    hw_write32(I2C1 + 0x1c, I2C_STOPF);
    hw_write32(I2C1 + 4, 0);
    if (value == 0xffffu && st == 0xffu) { last_faults = SENSING_FAULT_ENCODER_INVALID; return false; }
    *raw = value; *status = st;   /* caller judges range and magnet bits */
    return true;
fail:
    i2c_cleanup();
    return false;
}

/* Single-byte register read (AS5600 STATUS 0x0B). Own transaction, own STOP. */
bool sensing_read_encoder_status_byte(uint8_t *status)
{
    last_faults = 0;
    if (!status) { last_faults = SENSING_FAULT_ARGUMENT; return false; }
    if (!initialized) { last_faults = SENSING_FAULT_NOT_INITIALIZED; return false; }
    uint32_t start = hw_micros();
    if (!i2c_wait(I2C_BUSY, false, start)) goto fail;
    hw_write32(I2C1 + 0x1c, I2C_CLEAR);
    hw_write32(I2C1 + 4, 0x0001206cu);
    if (!i2c_wait(2, true, start)) goto fail;
    hw_write32(I2C1 + 0x28, 0x0bu);
    if (!i2c_wait(0x40, true, start)) goto fail;
    hw_write32(I2C1 + 4, 0x0201246cu); /* Read1, repeated START, AUTOEND. */
    if (!i2c_wait(4, true, start)) goto fail;
    uint8_t st = (uint8_t)(hw_read32(I2C1 + 0x24) & 255u);
    if (!i2c_wait(I2C_STOPF, true, start)) goto fail;
    hw_write32(I2C1 + 0x1c, I2C_STOPF);
    hw_write32(I2C1 + 4, 0);
    *status = st;
    return true;
fail:
    i2c_cleanup();
    return false;
}

bool sensing_read_encoder(uint16_t *raw)
{
    last_faults = 0;
    if (!raw) { last_faults = SENSING_FAULT_ARGUMENT; return false; }
    *raw = 0;
    if (!initialized) { last_faults = SENSING_FAULT_NOT_INITIALIZED; return false; }
    uint16_t word;
    if (!i2c_read_word(0x0c, &word)) return false;
    if (word == 0xffffu) { last_faults = SENSING_FAULT_ENCODER_INVALID; return false; }
    last_encoder_word = word;
    *raw = word & 0x0fffu;
    return true;
}
uint16_t sensing_last_encoder_word(void) { return last_encoder_word; }

/* Deliberately specific: this writer cannot address OTP or calibration fields. */
static bool encoder_write_conf(uint16_t word)
{
    uint32_t start = hw_micros();
    if (!i2c_wait(I2C_BUSY, false, start)) goto fail;
    hw_write32(I2C1 + 0x1c, I2C_CLEAR);
    hw_write32(I2C1 + 4, 0x0203206cu); /* Address36, write3, START/AUTOEND. */
    if (!i2c_wait(2, true, start)) goto fail;
    hw_write32(I2C1 + 0x28, 0x07u);
    if (!i2c_wait(2, true, start)) goto fail;
    hw_write32(I2C1 + 0x28, word >> 8);
    if (!i2c_wait(2, true, start)) goto fail;
    hw_write32(I2C1 + 0x28, word & 255u);
    if (!i2c_wait(I2C_STOPF, true, start)) goto fail;
    hw_write32(I2C1 + 0x1c, I2C_STOPF);
    hw_write32(I2C1 + 4, 0);
    return true;
fail:
    i2c_cleanup();
    return false;
}

/* Keep the saved value until a complete write/readback proves restoration.
 * This helper deliberately retains earlier failure bits during rollback. */
static bool encoder_restore_saved(void)
{
    if (!sensor_conf_saved) return true;
    uint16_t observed;
    if (!encoder_write_conf(sensor_conf_original) ||
        !i2c_read_word(0x07u, &observed)) {
        last_faults |= SENSING_FAULT_ENCODER_RESTORE;
        return false;
    }
    if (observed != sensor_conf_original) {
        last_faults |= SENSING_FAULT_ENCODER_RESTORE;
        return false;
    }
    sensor_conf_saved = false;
    return true;
}

bool sensing_encoder_restore(void)
{
    last_faults = 0;
    if (!sensor_conf_saved) return true; /* Also safe before any configuration. */
    if (!initialized) { last_faults = SENSING_FAULT_NOT_INITIALIZED; return false; }
    return encoder_restore_saved();
}

bool sensing_encoder_config(uint16_t *before, uint16_t *after)
{
    last_faults = 0;
    if (before) *before = 0;
    if (after) *after = 0;
    if (!before || !after) { last_faults = SENSING_FAULT_ARGUMENT; return false; }
    if (!initialized) { last_faults = SENSING_FAULT_NOT_INITIALIZED; return false; }
    uint16_t original, observed;
    if (!i2c_read_word(0x07u, &original)) return false;
    *before = original;
    if (original == 0xffffu) { last_faults = SENSING_FAULT_ENCODER_INVALID; return false; }
    /* AS5600 CONF: NOM, SF11, FTH000, WD0. Preserve HYST, output-stage,
     * PWM-frequency and reserved/factory bits. Never access BURN registerFF.
     * ams datasheet v1-06 pp18/19/28/29: volatile until SENSOR power loss.
     * MCU reset/F9 leaves the powered sensor registers unchanged. */
    uint16_t desired = (uint16_t)((original & (uint16_t)~0x3f03u) | 0x0300u);
    if (!sensor_conf_saved) {
        sensor_conf_original = original;
        sensor_conf_saved = true; /* BEFORE any potentially partial write. */
    }
    if (!encoder_write_conf(desired)) goto rollback;
    if (!i2c_read_word(0x07u, &observed)) goto rollback;
    *after = observed;
    if (observed != desired) {
        last_faults = SENSING_FAULT_ENCODER_CONFIG;
        goto rollback;
    }
    return true;
rollback:
    (void)encoder_restore_saved(); /* Best effort; retain failure and retry state. */
    return false;
}

static bool adc_wait(uint32_t mask, uint32_t start, uint32_t budget)
{
    for (;;) {
        uint32_t status = hw_read32(ADC1);
        if (expired(start, budget)) { last_faults |= SENSING_FAULT_ADC_TIMEOUT; return false; }
        if (status & ADC_OVR) { last_faults |= SENSING_FAULT_ADC_OVERRUN; return false; }
        if ((status & mask) == mask) return true;
        hw_relax();
    }
}

static bool adc_convert(unsigned channel, uint16_t *sample, uint32_t start, uint32_t budget)
{
    hw_write32(ADC1, ADC_CLEAR);
    hw_write32(ADC1 + 0x28, 1u << channel);
    if (!adc_wait(ADC_CCRDY, start, budget)) return false;
    modify(ADC1 + 8, 0, ADC_START);
    if (!adc_wait(ADC_EOC, start, budget)) return false;
    uint16_t raw = (uint16_t)(hw_read32(ADC1 + 0x40) & 0xfffu);
    if (expired(start, budget)) { last_faults |= SENSING_FAULT_ADC_TIMEOUT; return false; }
    *sample = raw;
    return true;
}

static void adc_cleanup(void)
{
    if (hw_read32(ADC1 + 8) & ADC_START) {
        modify(ADC1 + 8, 0, ADC_STOP);
        if (!wait_register(ADC1 + 8, ADC_START, false, hw_micros(), ADC_CLEANUP_US)) {
            reset_peripheral(RCC + 0x30, ADC_CLOCK);
            adc_usable = false; /* Require reinitialization after unacknowledged stop. */
        }
    }
    hw_write32(ADC1, ADC_CLEAR);
}

static bool adc_derive(sensing_adc *sample)
{
    if (!sample->raw_reference) { last_faults = SENSING_FAULT_ADC_REFERENCE; return false; }
    sample->current_magnitude_ma = (uint16_t)(((uint32_t)sample->raw_current * 825u) >> 9);
    uint32_t voltage = ((uint32_t)sample->raw_voltage * 3036u) / (33u * sample->raw_reference) + 1u;
    sample->voltage_decivolts = (uint16_t)(voltage > 65535u ? 65535u : voltage);
    unsigned index = ((unsigned)sample->raw_temperature + 200u) >> 4;
    if (index > 164u) index = 164u; /* Bound before conversion: stock uint8 wraps. */
    sample->temperature_c = temperature_lut[index];
    return true;
}

bool sensing_read_adc(sensing_adc *out)
{
    last_faults = 0;
    adc_cache_invalidate(); /* A failed full acquisition cannot leave an old seed. */
    if (!out) { last_faults = SENSING_FAULT_ARGUMENT; return false; }
    *out = (sensing_adc){0};
    if (!initialized || !adc_usable) {
        last_faults = SENSING_FAULT_NOT_INITIALIZED;
        out->faults = last_faults;
        return false;
    }
    sensing_adc sample = {0};
    uint32_t start = hw_micros();
    if (!wait_register(ADC1 + 8, ADC_START, false, start, ADC_BUDGET_US)) {
        last_faults = SENSING_FAULT_ADC_TIMEOUT;
        goto fail;
    }
    if (!adc_convert(13, &sample.raw_reference, start, ADC_BUDGET_US) ||
        !adc_convert(0, &sample.raw_temperature, start, ADC_BUDGET_US) ||
        !adc_convert(1, &sample.raw_voltage, start, ADC_BUDGET_US) ||
        !adc_convert(9, &sample.raw_current, start, ADC_BUDGET_US)) goto fail;
    if (!adc_derive(&sample)) goto fail;
    sample.timestamp_us = hw_micros();
    adc_cache = sample;
    adc_cache_valid = true;
    *out = sample;
    return true;
fail:
    adc_cleanup();
    out->faults = last_faults;
    return false;
}

bool sensing_read_adc_tick(sensing_adc *out)
{
    last_faults = 0;
    if (!out) {
        adc_cache_invalidate();
        last_faults = SENSING_FAULT_ARGUMENT;
        return false;
    }
    *out = (sensing_adc){0};
    if (!initialized || !adc_usable || !adc_cache_valid) {
        adc_cache_invalidate();
        last_faults = SENSING_FAULT_NOT_INITIALIZED;
        out->faults = last_faults;
        return false;
    }
    static const uint8_t channels[4] = {13u, 0u, 1u, 9u};
    sensing_adc sample = adc_cache;
    uint32_t start = hw_micros();
    if (!wait_register(ADC1 + 8, ADC_START, false, start, ADC_TICK_BUDGET_US)) {
        last_faults = SENSING_FAULT_ADC_TIMEOUT;
        goto fail;
    }
    uint16_t raw;
    if (!adc_convert(channels[adc_tick_at], &raw, start, ADC_TICK_BUDGET_US)) goto fail;
    /* Other three channels retain their measured raw values; this timestamp
     * belongs only to the newest conversion, never a simultaneous sample. */
    sample.timestamp_us = hw_micros();
    switch (adc_tick_at) {
    case 0u: sample.raw_reference = raw; break;
    case 1u: sample.raw_temperature = raw; break;
    case 2u: sample.raw_voltage = raw; break;
    default: sample.raw_current = raw; break;
    }
    if (!adc_derive(&sample)) goto fail;
    adc_cache = sample;
    adc_tick_at = (adc_tick_at + 1u) & 3u;
    *out = sample;
    return true;
fail:
    adc_cache_invalidate();
    adc_cleanup();
    out->faults = last_faults;
    return false;
}

uint32_t sensing_last_faults(void) { return last_faults; }
